-- 0014 : module 2 (gestion des opérations), étape 1.
-- Référentiels issus du modèle « GFE - COMPTABLE - MODELE VIERGE » :
--   plan_modele      : plan de comptes du cabinet (PLAN, 1 258 comptes), copié dans chaque entreprise
--   types_operation  : types d'opération (PARAM K:Q, 18 types dont 3 OD)
-- Tables par entreprise : plan_comptes (copie du plan, modifiable par le comptable).
-- Idempotente. Lecture seule pour les référentiels ; écriture réservée aux chefs.

-- 1. Référentiels (lecture pour tout compte connecté)
create table if not exists gfe.plan_modele (
  numero_interne text primary key,
  numero_affiche text not null,
  libelle text not null,
  classe text,
  nature text
);
alter table gfe.plan_modele enable row level security;
drop policy if exists "plan modèle lisible" on gfe.plan_modele;
create policy "plan modèle lisible" on gfe.plan_modele for select to authenticated using (true);

create table if not exists gfe.types_operation (
  code text primary key,
  libelle text not null,
  mode_requis int not null,        -- 1 = mode requis (Espèces/Banque), 0 = non
  categorie_requise int not null,  -- 1 = catégorie requise, 0 = non
  tiers int not null,              -- 1 requis, 2 optionnel, 0 non utilisé
  est_od boolean not null default false,
  sortie_especes boolean not null default false,
  compte_od_debit text,            -- compte débit fixé (OD uniquement)
  compte_od_credit text            -- compte crédit fixé (OD uniquement)
);
alter table gfe.types_operation enable row level security;
drop policy if exists "types lisibles" on gfe.types_operation;
create policy "types lisibles" on gfe.types_operation for select to authenticated using (true);

-- 2. Plan de comptes par entreprise (copie modifiable)
create table if not exists gfe.plan_comptes (
  entreprise_id uuid not null references gfe.entreprises(id) on delete cascade,
  numero_interne text not null,
  numero_affiche text not null,
  libelle text not null,
  classe text,
  nature text,
  solde_ouverture numeric not null default 0,   -- débit +, crédit -
  primary key (entreprise_id, numero_interne)
);
alter table gfe.plan_comptes enable row level security;
drop policy if exists "plan voit membre" on gfe.plan_comptes;
create policy "plan voit membre" on gfe.plan_comptes for select to authenticated
  using (gfe.est_membre(entreprise_id));
drop policy if exists "plan modifie comptable" on gfe.plan_comptes;
create policy "plan modifie comptable" on gfe.plan_comptes for all to authenticated
  using (gfe.est_comptable_de(entreprise_id)) with check (gfe.est_comptable_de(entreprise_id));

-- 3. Initialisation du plan d'une entreprise à partir du modèle (idempotente)
create or replace function gfe.initialiser_plan(p_entreprise uuid) returns int
language plpgsql security definer set search_path = gfe, public as $$
declare n int;
begin
  if not gfe.est_comptable_de(p_entreprise) then
    raise exception 'Réservé au comptable de cette entreprise ou à un chef';
  end if;
  insert into gfe.plan_comptes (entreprise_id, numero_interne, numero_affiche, libelle, classe, nature)
  select p_entreprise, m.numero_interne, m.numero_affiche, m.libelle, m.classe, m.nature
  from gfe.plan_modele m
  on conflict (entreprise_id, numero_interne) do nothing;
  get diagnostics n = row_count;
  return n;
end $$;

grant execute on function gfe.initialiser_plan(uuid) to authenticated;
revoke all on function gfe.initialiser_plan(uuid) from anon, public;

